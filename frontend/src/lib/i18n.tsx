interface I18nState {
  locale: Locale;
  setLocale: (locale: Locale) => void;
  t: (key: string, values?: Record<string, string | number>) => string;
}

const I18nContext = createContext<I18nState | null>(null);

function initialLocale(): Locale {
  if (typeof window === "undefined") return "zh-CN";
  const stored = window.localStorage.getItem(STORAGE_KEY);
  return stored === "ja-JP" || stored === "zh-CN" ? stored : "zh-CN";
}

export function I18nProvider({ children }: { children: ReactNode }) {
  const [locale, setLocaleState] = useState<Locale>(() => initialLocale());

  const setLocale = (next: Locale) => {
    setLocaleState(next);
    window.localStorage.setItem(STORAGE_KEY, next);
  };

  useEffect(() => {
    document.documentElement.lang = locale;
  }, [locale]);

  const value = useMemo<I18nState>(
    () => ({
      locale,
      setLocale,
      t: (key, values) => {
        const template = dictionaries[locale][key] ?? dictionaries["zh-CN"][key] ?? key;
        if (!values) return template;
        return template.replace(/\{(\w+)\}/g, (_, name: string) =>
          String(values[name] ?? ""),
        );
      },
    }),
    [locale],
  );

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n(): I18nState {
  const ctx = useContext(I18nContext);
  if (!ctx) throw new Error("useI18n must be used within I18nProvider");
  return ctx;
}

export function LanguageSelect({ compact = false }: { compact?: boolean }) {
  const { locale, setLocale, t } = useI18n();
  return (
    <label className={`language-select ${compact ? "compact" : ""}`}>
      {!compact && <span>{t("language")}</span>}
      <select
        className="input"
        value={locale}
        onChange={(event) => setLocale(event.target.value as Locale)}
        aria-label={t("language")}
      >
        <option value="zh-CN">{t("chinese")}</option>
        <option value="ja-JP">{t("japanese")}</option>
      </select>
    </label>
  );
}
